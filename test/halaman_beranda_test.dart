import 'dart:async';
import 'dart:io';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:project_tride/Models/user_model.dart';
import 'package:project_tride/Views/halaman beranda/halaman_beranda.dart';

void main() {
  testWidgets('HalamanBeranda renders all sections correctly',
      (WidgetTester tester) async {
    await HttpOverrides.runWithHttpOverrides(() async {
      final user = UserModel(
        id: 1,
        nama: 'Andi',
        email: 'andi@example.com',
        password: 'password123',
      );

      await tester.pumpWidget(
        MaterialApp(
          home: HalamanBeranda(user: user),
        ),
      );
      await tester.pump();

      // Verify Header & Greeting
      expect(find.text('Trips'), findsOneWidget);
      expect(find.text('Good morning, Andi'), findsOneWidget);

      // Verify Search Hint & AI Entry
      expect(find.text('Where to?'), findsOneWidget);
      expect(find.text('Plan a trip with AI'), findsOneWidget);

      // Verify Section Titles
      expect(find.text('Upcoming Trip'), findsOneWidget);
      expect(find.text('Destinasi Populer'), findsOneWidget);
      expect(find.text('Jelajahi Berdasarkan Pengalaman'), findsOneWidget);

      // Verify Bottom Navigation Bar is present
      expect(find.byType(HalamanBeranda), findsOneWidget);
    }, _TestHttpOverrides());
  });
}

class _TestHttpOverrides extends HttpOverrides {
  @override
  HttpClient createHttpClient(SecurityContext? context) {
    return _MockHttpClient();
  }
}

class _MockHttpClient extends Fake implements HttpClient {
  @override
  bool autoUncompress = true;
  @override
  Duration? connectionTimeout;
  @override
  Duration idleTimeout = const Duration(seconds: 15);
  @override
  int? maxConnectionsPerHost;
  @override
  String? userAgent;

  @override
  Future<HttpClientRequest> getUrl(Uri url) async => _MockHttpClientRequest();
  @override
  Future<HttpClientRequest> openUrl(String method, Uri url) async =>
      _MockHttpClientRequest();
}

class _MockHttpClientRequest extends Fake implements HttpClientRequest {
  @override
  final HttpHeaders headers = _MockHttpHeaders();
  @override
  Future<HttpClientResponse> close() async => _MockHttpClientResponse();
}

class _MockHttpHeaders extends Fake implements HttpHeaders {
  @override
  void set(String name, Object value, {bool preserveHeaderCase = false}) {}
}

class _MockHttpClientResponse extends Fake implements HttpClientResponse {
  @override
  int get statusCode => 200;
  @override
  int get contentLength => _transparentImage.length;
  @override
  HttpClientResponseCompressionState get compressionState =>
      HttpClientResponseCompressionState.notCompressed;

  @override
  StreamSubscription<List<int>> listen(
    void Function(List<int> event)? onData, {
    Function? onError,
    void Function()? onDone,
    bool? cancelOnError,
  }) {
    return Stream<List<int>>.value(_transparentImage).listen(
      onData,
      onError: onError,
      onDone: onDone,
      cancelOnError: cancelOnError,
    );
  }
}

